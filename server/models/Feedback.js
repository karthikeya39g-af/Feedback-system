const mongoose = require('mongoose');

const feedbackSchema = new mongoose.Schema({
    id: { type: String }, // optional, auto-generated by mongo usually but keeping for parity
    timestamp: { type: Date, default: Date.now },

    rollnumber: { type: String, required: true },
    name: { type: String },

    // Link to Subject metadata
    subject: { type: String, required: true },
    subjectId: { type: String, required: true },
    faculty: { type: String, required: true },
    type: { type: String, enum: ['theory', 'lab'], required: true },

    class: { type: String, required: true },
    section: { type: String, required: true },
    semester: { type: String, required: true },

    // Ratings: Flexible object map since parameters might change (P1..P10, L1..L8)
    ratings: { type: Map, of: Number },

    comment: { type: String }
}, { timestamps: true });

// Compound index to prevent duplicate submissions
feedbackSchema.index({ rollnumber: 1, subjectId: 1 }, { unique: true });

module.exports = mongoose.models.Feedback || mongoose.model('Feedback', feedbackSchema);
